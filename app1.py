import streamlit as st
import pandas as pd
import joblib

# ===========================
# Load trained pipeline
# ===========================
pipeline = joblib.load("heart_disease_pipeline.pkl")

# ===========================
# Load dataset
# ===========================
df = pd.read_csv("heart-disease ITP (1).csv")

st.set_page_config(page_title="Heart Disease Prediction", page_icon="❤️")

st.title("❤️ Heart Disease Prediction System")
st.write("Enter the patient's details below.")

# ===========================
# User Inputs
# ===========================

age = st.slider(
    "Age",
    int(df["age"].min()),
    int(df["age"].max()),
    int(df["age"].median())
)

sex = st.selectbox(
    "Sex",
    [0, 1],
    format_func=lambda x: "Female" if x == 0 else "Male"
)

cp = st.selectbox(
    "Chest Pain Type (cp)",
    [0, 1, 2, 3]
)

trestbps = st.slider(
    "Resting Blood Pressure",
    int(df["trestbps"].min()),
    int(df["trestbps"].max()),
    int(df["trestbps"].median())
)

chol = st.slider(
    "Cholesterol",
    int(df["chol"].min()),
    int(df["chol"].max()),
    int(df["chol"].median())
)

fbs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dl",
    [0, 1]
)

restecg = st.selectbox(
    "Resting ECG",
    sorted(df["restecg"].unique())
)

thalach = st.slider(
    "Maximum Heart Rate Achieved",
    int(df["thalach"].min()),
    int(df["thalach"].max()),
    int(df["thalach"].median())
)

exang = st.selectbox(
    "Exercise Induced Angina",
    [0, 1]
)

oldpeak = st.slider(
    "Oldpeak",
    float(df["oldpeak"].min()),
    float(df["oldpeak"].max()),
    float(df["oldpeak"].median()),
    step=0.1
)

slope = st.selectbox(
    "Slope",
    sorted(df["slope"].unique())
)

ca = st.selectbox(
    "Number of Major Vessels (ca)",
    sorted(df["ca"].unique())
)

thal = st.selectbox(
    "Thal",
    sorted(df["thal"].unique())
)

# ===========================
# Create DataFrame
# ===========================

input_df = pd.DataFrame({
    "age":[age],
    "sex":[sex],
    "cp":[cp],
    "trestbps":[trestbps],
    "chol":[chol],
    "fbs":[fbs],
    "restecg":[restecg],
    "thalach":[thalach],
    "exang":[exang],
    "oldpeak":[oldpeak],
    "slope":[slope],
    "ca":[ca],
    "thal":[thal]
})

# ===========================
# Prediction
# ===========================

if st.button("Predict Heart Disease"):

    prediction = pipeline.predict(input_df)
    probability = pipeline.predict_proba(input_df)

    heart_prob = probability[0][1] * 100
    healthy_prob = probability[0][0] * 100

    st.subheader("Prediction Result")

    if prediction[0] == 1:
        st.error("⚠️ Higher Possibility of Heart Disease")
    else:
        st.success("✅ Lower Possibility of Heart Disease")

    st.write(f"**Heart Disease Probability:** {heart_prob:.2f}%")
    st.write(f"**No Heart Disease Probability:** {healthy_prob:.2f}%")

    st.progress(int(heart_prob))

    st.info(
        "⚠️ Disclaimer: This prediction is generated by a Machine Learning model "
        "for educational purposes only. It should not be considered a medical diagnosis. "
        "Please consult a qualified healthcare professional for proper medical advice."
    )